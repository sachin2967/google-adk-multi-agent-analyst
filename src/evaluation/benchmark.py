"""Independent SQL cross-checks for deterministic MCP aggregation contracts."""

from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

from src.tools.mcp_tools import query_metrics


def run_tool_regression(db_path: Path) -> dict[str, Any]:
    """Compare MCP tool aggregates to independent reference SQL.

    This evaluates data-tool semantics on the generated fixture, not agent intent
    understanding, answer quality, production latency, or external data validity.
    """
    connection = sqlite3.connect(db_path)
    checks: list[dict[str, Any]] = []
    try:
        expected_revenue = connection.execute(
            "SELECT SUM(oi.price * oi.quantity) FROM orders o JOIN order_items oi ON oi.order_id=o.order_id WHERE o.order_status='delivered'"
        ).fetchone()[0]
        actual_revenue = query_metrics("revenue", "category", db_path=db_path)
        checks.append(
            {
                "name": "delivered_revenue_by_category_matches_independent_total",
                "passed": abs(
                    sum(row["value"] for row in actual_revenue["records"])
                    - expected_revenue
                )
                < 0.01,
                "expected": round(expected_revenue, 2),
                "actual": round(
                    sum(row["value"] for row in actual_revenue["records"]), 2
                ),
            }
        )

        expected_status = dict(
            connection.execute(
                "SELECT order_status, COUNT(*) FROM orders GROUP BY order_status"
            )
        )
        actual_status = query_metrics("orders", "status", db_path=db_path)
        actual_status_map = {
            row["group_value"]: row["value"] for row in actual_status["records"]
        }
        checks.append(
            {
                "name": "order_counts_by_status_match_independent_query",
                "passed": actual_status_map == expected_status,
                "expected": expected_status,
                "actual": actual_status_map,
            }
        )

        expected_reviews = connection.execute(
            "SELECT AVG(review_score) FROM reviews"
        ).fetchone()[0]
        actual_reviews = query_metrics("average_review", db_path=db_path)["records"][0][
            "value"
        ]
        checks.append(
            {
                "name": "overall_average_review_matches_independent_query",
                "passed": abs(actual_reviews - expected_reviews) < 1e-9,
                "expected": expected_reviews,
                "actual": actual_reviews,
            }
        )

        expected_states = dict(
            connection.execute(
                "SELECT c.customer_state, COUNT(DISTINCT o.order_id) FROM orders o JOIN customers c ON c.customer_id=o.customer_id GROUP BY c.customer_state"
            )
        )
        actual_states = query_metrics("orders", "state", db_path=db_path)
        actual_state_map = {
            row["group_value"]: row["value"] for row in actual_states["records"]
        }
        checks.append(
            {
                "name": "order_counts_by_state_match_independent_query",
                "passed": actual_state_map == expected_states,
                "expected": expected_states,
                "actual": actual_state_map,
            }
        )
    finally:
        connection.close()

    return {
        "evaluation_type": "deterministic MCP tool regression",
        "dataset": "seeded synthetic commerce fixture generated by data/create_db.py",
        "scope": "cross-check supported aggregate semantics against independent SQL",
        "not_evaluated": [
            "LLM tool selection",
            "natural-language semantic accuracy",
            "factual answer quality",
            "production-scale latency",
        ],
        "checks_passed": sum(check["passed"] for check in checks),
        "checks_total": len(checks),
        "checks": checks,
    }
